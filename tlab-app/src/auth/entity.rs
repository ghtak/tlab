use sqlx::types::time::OffsetDateTime;

#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, sqlx::Type)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
#[sqlx(type_name = "text", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum AccountStatus {
    Registered,
    Active,
    Withdrawn,
}

/// Providers supported by this application version. The DB column remains TEXT.
#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::Type)]
#[sqlx(type_name = "text", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Provider {
    Local,
    Google,
    Kakao,
}

/// Account values supplied for insertion. IDs and audit times are generated by the DB.
pub struct NewAccount {
    pub nickname: String,
    pub status: AccountStatus,
    pub withdrawn_at: Option<OffsetDateTime>,
}

#[derive(sqlx::FromRow)]
#[allow(
    dead_code,
    reason = "Persistence entities include the complete stored row, beyond fields read by the creation slice"
)]
pub struct Account {
    pub id: i64,
    pub nickname: String,
    pub status: AccountStatus,
    pub withdrawn_at: Option<OffsetDateTime>,
    pub created_at: OffsetDateTime,
    pub updated_at: OffsetDateTime,
}

// No Debug or Serialize: identity entities contain password hashes.
pub struct NewIdentity {
    pub account_id: i64,
    pub priority: i32,
    pub provider: Provider,
    pub provider_subject: Option<String>,
    pub email: String,
    pub email_verified_at: Option<OffsetDateTime>,
    pub password_hash: Option<String>,
}

#[derive(sqlx::FromRow)]
#[allow(
    dead_code,
    reason = "Persistence entities include the complete stored row, beyond fields read by the creation slice"
)]
pub struct Identity {
    pub id: i64,
    pub account_id: i64,
    pub priority: i32,
    pub provider: Provider,
    pub provider_subject: Option<String>,
    pub email: String,
    pub email_verified_at: Option<OffsetDateTime>,
    pub password_hash: Option<String>,
    pub created_at: OffsetDateTime,
    pub updated_at: OffsetDateTime,
}
