use chrono::{DateTime, Utc};
use uuid::Uuid;

use super::token::RefreshHash;

#[derive(Clone, Copy, sqlx::Type)]
#[sqlx(type_name = "text", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum RevokeReason {
    Logout,
    AccountSuspended,
    AccountWithdrawn,
}

/// Times and session ID are supplied by the caller after obtaining its locks.
pub struct NewRefreshToken {
    pub session_id: Uuid,
    pub account_id: i64,
    pub token_hash: RefreshHash,
    pub session_created_at: DateTime<Utc>,
    pub session_expires_at: DateTime<Utc>,
    pub created_at: DateTime<Utc>,
    pub expires_at: DateTime<Utc>,
}

// No Debug or Serialize: the hash is token-derived material.
#[derive(sqlx::FromRow)]
#[allow(
    dead_code,
    reason = "Complete stored row used by later authentication slices"
)]
pub struct RefreshToken {
    pub id: i64,
    pub session_id: Uuid,
    pub account_id: i64,
    pub token_hash: Vec<u8>,
    pub session_created_at: DateTime<Utc>,
    pub session_expires_at: DateTime<Utc>,
    pub created_at: DateTime<Utc>,
    pub expires_at: DateTime<Utc>,
    pub revoked_at: Option<DateTime<Utc>>,
    pub revoke_reason: Option<RevokeReason>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, sqlx::Type)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
#[sqlx(type_name = "text", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum AccountStatus {
    Registered,
    Active,
    Withdrawn,
}

/// Providers supported by this application version. The DB column remains TEXT.
#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::Type)]
#[sqlx(type_name = "text", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Provider {
    Local,
    Google,
    Kakao,
}

/// Account values supplied for insertion. IDs and audit times are generated by the DB.
pub struct NewAccount {
    pub nickname: String,
    pub status: AccountStatus,
    pub withdrawn_at: Option<DateTime<Utc>>,
}

#[derive(sqlx::FromRow)]
#[allow(
    dead_code,
    reason = "Persistence entities include the complete stored row, beyond fields read by the creation slice"
)]
pub struct Account {
    pub id: i64,
    pub nickname: String,
    pub status: AccountStatus,
    pub withdrawn_at: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

// No Debug or Serialize: identity entities contain password hashes.
pub struct NewIdentity {
    pub account_id: i64,
    pub priority: i32,
    pub provider: Provider,
    pub provider_subject: Option<String>,
    pub email: String,
    pub email_verified_at: Option<DateTime<Utc>>,
    pub password_hash: Option<String>,
}

#[derive(sqlx::FromRow)]
#[allow(
    dead_code,
    reason = "Persistence entities include the complete stored row, beyond fields read by the creation slice"
)]
pub struct Identity {
    pub id: i64,
    pub account_id: i64,
    pub priority: i32,
    pub provider: Provider,
    pub provider_subject: Option<String>,
    pub email: String,
    pub email_verified_at: Option<DateTime<Utc>>,
    pub password_hash: Option<String>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}
